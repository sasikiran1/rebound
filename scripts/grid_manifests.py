"""Write the section 7a gate grid manifests (exploration only): tokens 1x or 1.5x pool, queue wait 1.0 or 1.5 s."""

from pathlib import Path

import yaml

base_path = Path("manifests/exploratory/explore_v1.yaml")
base = yaml.safe_load(base_path.read_text())
pool = base["resources"]["pool_size"]
for tokens in (pool, int(pool * 1.5)):
    for wait_ms in (1000, 1500):
        m = {**base, "gate": {"tokens": tokens, "queue_max": 2 * tokens, "queue_wait_ms": wait_ms, "retry_after_s": 2}}
        out = Path(f"manifests/exploratory/grid_t{tokens}_w{wait_ms}.yaml")
        out.write_text("# Gate grid point (exploration, generated by scripts/grid_manifests.py)\n"
                       + yaml.safe_dump(m, sort_keys=False, default_flow_style=None, width=120))
        print(out)
