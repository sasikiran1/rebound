# ruff: noqa: E501 (the customer messages below are kept on one line each)
"""Write the hardened agent's tool set and the free-text task set (run once; outputs are committed).

prompts/tools_v3.json = tools_v2_time.json + record_requirements (harness only; the adapter enforces it).
data/tasks/tasks_messy_v1.jsonl = customer messages in plain language, built from task set B. Each task keeps a
structured `constraint` for the oracle; the agent sees only the message. Message wording is hand-written below,
not generated by a model. Feasibility comes from SQL on fielddesk_template. Half the tasks of each kind are held out.
"""

import asyncio
import copy
import datetime as dt
import json
import random
import sys
from pathlib import Path

import asyncpg

sys.path.insert(0, ".")
from harness import settings  # noqa: E402
from oracle.verdicts import CANDIDATES, meets_constraint  # noqa: E402

AFTERNOON = [
    "Hi, it's about my {service} on {current}. Can you move it to {d1}? I'm at work until 3, so it has to be 3 pm or later, and before 4.",
    "Need to shift my {service} from {current} to {d1}. Mornings and lunchtime are out, I can only do the 3 o'clock hour.",
    "Could we push the {service} booked for {current} to {d1}? Anything from three onwards works but it must start before four.",
]
MORNING = [
    "My {service} on {current} doesn't work anymore. Can you move it to {d1}? I have to leave by 10, so it must start before 10 am.",
    "Please rebook the {service} from {current} for {d1}, early please, starting before ten. I'm out the rest of the day.",
]
TECH = [
    "Please move my {service} from {current} to sometime {d1} to {d2}. Last time technician {tech} did a great job and I only want them.",
    "I'd like to rebook the {service} on {current} for between {d1} and {d2}, but only with technician number {tech}, nobody else knows my system.",
]
IMPOSSIBLE = [
    "Can you move my {service} from {current} to {d1}? I can only do the 6 pm hour because of work, nothing earlier.",
    "Hi, please shift the {service} on {current} to {d1}, but it has to start at 7 in the morning, I leave right after.",
]


def build_tools() -> None:
    tools = json.loads(Path("prompts/tools_v2_time.json").read_text())
    tools.append({
        "type": "function", "name": "record_requirements",
        "description": "Record what the customer requires beyond the date window. Call this before booking. Omit "
                       "what the customer did not ask for. Bookings that break these requirements are refused.",
        "parameters": {"type": "object", "additionalProperties": False, "properties": {
            "earliest_start": {"type": "string", "pattern": "^[0-2][0-9]:[0-5][0-9]$",
                               "description": "Earliest acceptable start time (HH:MM)."},
            "latest_start": {"type": "string", "pattern": "^[0-2][0-9]:[0-5][0-9]$",
                             "description": "The slot must start before this time (HH:MM)."},
            "technician_id": {"type": "integer", "description": "The only acceptable technician."}}},
    })
    Path("prompts/tools_v3.json").write_text(json.dumps(tools, indent=2) + "\n")


async def build_tasks() -> None:
    base = [json.loads(x) for x in Path("data/tasks/tasks_eval_B.jsonl").read_text().splitlines()]
    base = [t for t in base if t["expected"] == "reschedule"]
    rng = random.Random(20261101)
    rng.shuffle(base)
    conn = await asyncpg.connect(settings.oracle_dsn("fielddesk_template"))
    out, counts = [], {"afternoon": 0, "morning": 0, "technician": 0, "impossible": 0}
    want = {"afternoon": 12, "morning": 8, "technician": 8, "impossible": 8}

    def text(kind, tpl, t, **kw):
        return tpl.format(service=t["service"].replace("_", " "), current=t["current_date"], d1=t["d1"], d2=t["d2"], **kw)

    for t in base:
        rows = [dict(r) for r in await conn.fetch(CANDIDATES, t["customer_region"], t["service"],
                                                  dt.date.fromisoformat(t["d1"]), dt.date.fromisoformat(t["d2"]))]
        one_day = t["d1"] == t["d2"]
        for kind, c in (("afternoon", {"kind": "start_hour", "from_h": 15, "to_h": 16}),
                        ("morning", {"kind": "start_hour", "from_h": 0, "to_h": 10}),
                        ("impossible", {"kind": "start_hour", "from_h": 18, "to_h": 19})):
            if counts[kind] >= want[kind] or not one_day:
                continue
            ok = [r for r in rows if meets_constraint({"constraint": c}, r["id"], r["starts_at"], r["technician_id"])]
            if (kind == "impossible") != (len(ok) == 0) or not rows:
                continue
            pool = {"afternoon": AFTERNOON, "morning": MORNING, "impossible": IMPOSSIBLE}[kind]
            tpl = rng.choice(pool)
            if "7 in the morning" in tpl:  # this message asks for the 7 o'clock hour, not the 6 pm hour
                c = {"kind": "start_hour", "from_h": 7, "to_h": 8}
                ok = [r for r in rows if meets_constraint({"constraint": c}, r["id"], r["starts_at"], r["technician_id"])]
                assert not ok, "the 7 o'clock hour must be infeasible for an impossible task"
            task = copy.deepcopy(t)
            task.update(constraint=c, messy_kind=kind, feasible=len(ok),
                        goal_text=text(kind, tpl, t),
                        expected="defer" if kind == "impossible" else "reschedule",
                        task_id=f"M{kind[0].upper()}{counts[kind] + 1:02d}", base_task=t["task_id"],
                        split="held_out" if counts[kind] % 2 else "dev")
            out.append(task)
            counts[kind] += 1
            break
        else:
            if counts["technician"] < want["technician"] and not one_day and rows:
                tech = rng.choice(sorted({r["technician_id"] for r in rows}))
                task = copy.deepcopy(t)
                task.update(constraint={"kind": "technician", "technician_id": tech}, messy_kind="technician",
                            feasible=sum(r["technician_id"] == tech for r in rows),
                            goal_text=text("technician", rng.choice(TECH), t, tech=tech),
                            task_id=f"MT{counts['technician'] + 1:02d}", base_task=t["task_id"],
                            split="held_out" if counts["technician"] % 2 else "dev")
                out.append(task)
                counts["technician"] += 1
        if counts == want:
            break
    await conn.close()
    Path("data/tasks/tasks_messy_v1.jsonl").write_text("".join(json.dumps(t, sort_keys=True) + "\n" for t in out))
    print("tasks", counts)


build_tools()
asyncio.run(build_tasks())
